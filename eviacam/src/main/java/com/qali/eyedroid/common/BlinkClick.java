package com.qali.eyedroid.common;

import android.content.SharedPreferences;
import androidx.annotation.NonNull;

import com.qali.eyedroid.vision.PupilDetection;

/**
 * Turns a half blink (wink) of the configured eye into clicks and scroll drags.
 *
 * A quick wink generates a click. Keeping the eye half closed beyond the hold time
 * turns the wink into a drag: the content keeps scrolling (looking up or down moves
 * it) while the eye stays half closed, and the drag ends when the eye is opened
 * again. A held wink never generates a long click.
 *
 * The difference between the two eyes is used so that a normal (bidirectional) blink
 * does not generate clicks.
 */
public class BlinkClick implements SharedPreferences.OnSharedPreferenceChangeListener {

    /**
     * Receives the actions generated by the blink detector
     */
    public interface Listener {
        void onBlinkClick();

        /** the wink has been held long enough to become a drag instead of a click */
        void onBlinkHoldStart();

        /** the drag ends because the eye has been opened again */
        void onBlinkHoldEnd();

        void onBlinkScroll(boolean down);

        /**
         * @param pressed true when the wink starts, false when it ends
         */
        void onBlinkStateChanged(boolean pressed);
    }

    /* default wink score threshold, overridden from settings */
    private static final float DEFAULT_WINK_THRESHOLD = 0.45f;

    /* default time after which the wink becomes a drag (milliseconds) */
    private static final long DEFAULT_HOLD_TIME_MS = 600;

    /* gaze displacement (normalized) that starts scrolling while winking */
    private static final float SCROLL_GAZE_THRESHOLD = 0.015f;

    /* minimum time between two consecutive scroll actions */
    private static final long SCROLL_INTERVAL_MS = 250;

    private final Listener mListener;

    // whether the blink click function is enabled (from settings)
    private boolean mEnabled = false;

    // which eye generates the wink
    private boolean mRightEye = true;

    // thresholds (derived from settings)
    private float mWinkStart = DEFAULT_WINK_THRESHOLD;
    private float mWinkStartDifference = 0.25f;
    private float mWinkEnd = 0.30f;
    private float mWinkEndDifference = 0.12f;

    // time after which the wink becomes a drag instead of a click
    private long mHoldTime = DEFAULT_HOLD_TIME_MS;

    // the wink has been held long enough to be a drag (scrolling) right now
    private boolean mHolding = false;

    // state of the wink
    private boolean mWinking = false;
    private long mWinkStartTime = 0;
    private long mLastScrollTime = 0;

    // gaze height at the beginning of the wink, used as scroll reference
    private float mGazeBaseline = 0f;

    public BlinkClick(@NonNull Listener listener) {
        mListener = listener;
        Preferences.get().getSharedPreferences().registerOnSharedPreferenceChangeListener(this);
        updateSettings();
    }

    public void cleanup() {
        Preferences.get().getSharedPreferences().unregisterOnSharedPreferenceChangeListener(this);
    }

    @Override
    public void onSharedPreferenceChanged(SharedPreferences sharedPreferences, String key) {
        if (key.equals(Preferences.KEY_BLINK_CLICK) ||
                key.equals(Preferences.KEY_BLINK_EYE) ||
                key.equals(Preferences.KEY_BLINK_THRESHOLD) ||
                key.equals(Preferences.KEY_BLINK_HOLD_TIME)) {
            updateSettings();
        }
    }

    private void updateSettings() {
        final Preferences p = Preferences.get();

        mEnabled = p.getBlinkClick();
        mRightEye = p.getBlinkEye() == Preferences.BLINK_EYE_RIGHT;

        float threshold = p.getBlinkThreshold() / 100.0f;
        if (threshold <= 0f) threshold = DEFAULT_WINK_THRESHOLD;

        mWinkStart = threshold;
        mWinkStartDifference = Math.max(0.12f, threshold * 0.5f);
        mWinkEnd = Math.max(0.05f, threshold * 0.65f);
        mWinkEndDifference = Math.max(0.06f, threshold * 0.25f);

        mHoldTime = p.getBlinkHoldTime();

        if (!mEnabled) reset();
    }

    public boolean isEnabled() {
        return mEnabled;
    }

    /**
     * Reset the internal state
     */
    public void reset() {
        if (mHolding) {
            mHolding = false;
            mListener.onBlinkHoldEnd();
        }
        setWinking(false);
        mLastScrollTime = 0;
    }

    private void setWinking(boolean winking) {
        if (mWinking == winking) return;

        mWinking = winking;
        mListener.onBlinkStateChanged(winking);
    }

    /**
     * Update the state machine with a new pupil detection
     *
     * @param detection last pupil detection
     * @param clickable whether the pointer is over an actionable element
     *
     * NOTE: this method is called from a secondary thread
     */
    public void update(@NonNull PupilDetection detection, boolean clickable) {
        if (!mEnabled) {
            reset();
            return;
        }

        final long now = System.currentTimeMillis();
        final float active = mRightEye ? detection.blinkRight : detection.blinkLeft;
        final float other = mRightEye ? detection.blinkLeft : detection.blinkRight;

        final boolean winking =
                active >= mWinkStart && (active - other) >= mWinkStartDifference;
        final boolean released =
                active < mWinkEnd || (active - other) < mWinkEndDifference;

        if (!mWinking) {
            if (winking) {
                setWinking(true);
                mWinkStartTime = now;
                mLastScrollTime = 0;
                mGazeBaseline = detection.y;
                mHolding = false;
            }
            return;
        }

        if (released) {
            final boolean wasHolding = mHolding;
            mHolding = false;
            setWinking(false);
            mLastScrollTime = 0;

            /*
             * A held wink is a drag: it ends here, when the eye opens again, and it
             * never becomes a click nor a long click.
             */
            if (wasHolding) {
                mListener.onBlinkHoldEnd();
                return;
            }

            if (clickable) mListener.onBlinkClick();
            return;
        }

        /*
         * Still winking: once the hold time elapses the wink becomes a drag that keeps
         * scrolling until the eye is opened again.
         */
        if (!mHolding && (now - mWinkStartTime) >= mHoldTime) {
            mHolding = true;
            mLastScrollTime = 0;
            // the drag starts here: this gaze position is the scroll reference
            mGazeBaseline = detection.y;
            mListener.onBlinkHoldStart();
        }

        /*
         * A quick wink must stay a click, so scrolling only starts once the wink has
         * been held long enough to be a drag.
         */
        if (!mHolding) return;

        /* Still winking: use the gaze to scroll */
        final float dy = detection.y - mGazeBaseline;
        if (Math.abs(dy) < SCROLL_GAZE_THRESHOLD) {
            // back to the initial gaze, allow an immediate scroll in the other direction
            mLastScrollTime = 0;
            return;
        }
        if (mLastScrollTime != 0 && (now - mLastScrollTime) < SCROLL_INTERVAL_MS) return;

        mLastScrollTime = now;
        mListener.onBlinkScroll(dy > 0f);
    }
}
